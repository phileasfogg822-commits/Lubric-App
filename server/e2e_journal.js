/**
 * Proves the journal is a real double-entry ledger (spec §73).
 *
 * Spec §73: "Do not calculate financial reports independently from UI
 * transactions. Create a proper journal engine." Until now there was no engine
 * at all - `accounts` held two cash rows and ProfitLoss summed `expenses`
 * directly, so every report was a special case.
 *
 * What is checked:
 *   1. the chart of accounts exists and is classified
 *   2. the database REFUSES an unbalanced entry - the whole point of a journal
 *   3. a deferred check lets an entry and its lines be written in any order
 *   4. an entry with no lines is refused
 *   5. the same document cannot be posted twice
 *   6. the journal is append-only
 *   7. opening balances were posted and the Balance Sheet balances
 *
 * Run:  node e2e_journal.js
 *       API_BASE=http://localhost:3001
 */

const BASE = process.env.API_BASE || 'http://localhost:3001';

let ok = 0, total = 0;
async function check(title, fn) {
  total++;
  try {
    await fn();
    ok++;
    console.log('  PASS ' + title);
  } catch (e) {
    console.log('  FAIL ' + title + ': ' + e.message);
  }
}
function assert(c, m) {
  if (!c) throw new Error(m || 'assertion failed');
}
async function post(path, body, token) {
  const headers = { 'Content-Type': 'application/json' };
  if (token) headers.Authorization = 'Bearer ' + token;
  const res = await fetch(BASE + path, { method: 'POST', headers, body: JSON.stringify(body) });
  const text = await res.text();
  try { return { status: res.status, body: JSON.parse(text) }; }
  catch { return { status: res.status, body: text }; }
}
async function q(sql, params, token) {
  const { status, body } = await post('/api/query', { sql, params }, token);
  if (status !== 200) throw new Error('query ' + status + ' ' + JSON.stringify(body));
  return body;
}
async function exec(sql, params, token) {
  // /api/execute runs DML, so a thrown RAISE EXCEPTION comes back as a 500
  // carrying the database's own message.
  const { status, body } = await post('/api/execute', { sql, params }, token);
  return { status, body };
}
async function auth(email, pass) {
  const { status, body } = await post('/api/auth/login', { email, password: pass });
  if (status !== 200) throw new Error('auth failed: ' + status);
  return body.token;
}

console.log('\nDouble-entry journal (spec 73)');

const atok = await auth('admin@lubric.app', 'admin123');
const stamp = () => new Date().toISOString();
const uniq = (t) => t + '-' + Date.now() + '-' + Math.random().toString(36).slice(2, 8);

async function accId(code) {
  const r = await q('SELECT id FROM accounts WHERE shop_id = 1 AND code = $1', [code], atok);
  assert(r.length === 1, 'no account with code ' + code);
  return Number(r[0].id);
}

// An entry and its lines MUST be written in ONE transaction.
//
// The "entry has lines" and "debits equal credits" checks are DEFERRABLE
// constraint triggers, so they fire when the transaction COMMITS. Writing the
// entry and its lines as separate round trips means the first transaction
// commits an entry with no lines and the database refuses it - which is the
// guarantee working, not a bug.
//
// All of it therefore goes out as one parameterless simple-query string: a
// parameterless multi-statement query is wrapped by Postgres in a single
// implicit transaction, so the entry and every line are judged together. (With
// parameters node-postgres uses the extended protocol, which allows only one
// statement - hence no placeholders here. Every value below is generated by
// this test or read back from the database, so none of it is untrusted input.)
async function postEntry(kind, sourceId, lines) {
  const uuid = uniq('jrn');
  const sid = sourceId === null || sourceId === undefined ? 'NULL' : String(Number(sourceId));
  let sql =
    `INSERT INTO journal_entries (uuid, shop_id, kind, source_table, source_id, memo, entry_date) ` +
    `VALUES ('${uuid}', 1, '${kind}', 'e2e_journal', ${sid}, 'e2e test', CURRENT_DATE);`;
  lines.forEach((l, i) => {
    sql +=
      ` INSERT INTO journal_lines (entry_id, line_no, account_id, debit, credit, note) ` +
      `SELECT id, ${i + 1}, ${Number(l.account)}, ${Number(l.debit || 0)}, ` +
      `${Number(l.credit || 0)}, '${String(l.note || '').replace(/'/g, "''")}' ` +
      `FROM journal_entries WHERE uuid = '${uuid}';`;
  });
  const { status, body } = await exec(sql, null, atok);
  let id = null;
  if (status === 200) {
    const r = await q('SELECT id FROM journal_entries WHERE uuid = $1', [uuid], atok);
    id = r.length ? Number(r[0].id) : null;
  }
  return { status, body, id };
}



await check('the chart of accounts exists and is classified', async () => {
  const r = await q(
    "SELECT account_class, COUNT(*)::int AS n FROM accounts WHERE shop_id = 1 GROUP BY account_class ORDER BY 1",
    [], atok);
  const classes = r.map((x) => x.account_class);
  for (const need of ['asset', 'liability', 'equity', 'income', 'expense']) {
    assert(classes.includes(need), 'chart has no ' + need + ' account: ' + JSON.stringify(r));
  }
  for (const code of ['1000', '1100', '2000', '3000', '4000', '5000']) {
    await accId(code);
  }
});

await check('the database REFUSES an unbalanced entry', async () => {
  // This is the entire point of a journal. A ledger that will accept debits of
  // 100 against credits of 90 cannot produce a trustworthy balance sheet, and
  // no amount of correct reporting code fixes that.
  const cash = await accId('1000');
  const sales = await accId('4000');
  const before = await q('SELECT COUNT(*)::int AS c FROM journal_entries', [], atok);
  const e = await postEntry('other', null, [
    { account: cash, debit: 100 },
    { account: sales, credit: 90 },   // deliberately short
  ]);
  assert(e.status !== 200,
    'the unbalanced entry COMMITTED. The guarantee is not enforced: ' + JSON.stringify(e.body));
  assert(/balance/i.test(String(e.body && e.body.error)),
    'rejected, but not for the right reason: ' + JSON.stringify(e.body));
  const after = await q('SELECT COUNT(*)::int AS c FROM journal_entries', [], atok);
  assert(after[0].c === before[0].c, 'the entry was rolled back but left lines behind');
});

await check('a balanced entry is accepted', async () => {
  const cash = await accId('1000');
  const sales = await accId('4000');
  const e = await postEntry('other', null, [
    { account: sales, credit: 500 },
    { account: cash, debit: 500 },
  ]);
  assert(e.status === 200, 'a BALANCED entry was refused: ' + JSON.stringify(e.body));
  const r = await q('SELECT COALESCE(SUM(debit),0) d, COALESCE(SUM(credit),0) c FROM journal_lines WHERE entry_id = $1', [e.id], atok);
  assert(Number(r[0].d) === 500 && Number(r[0].c) === 500, 'lines did not commit');
  assert(Number(r[0].d) === 500, 'wrong total: ' + r[0].d);
});

await check('an entry with no lines is refused', async () => {
  // Zero equals zero, so the balance check alone would pass this happily.
  const r = await exec(
    `INSERT INTO journal_entries (uuid, shop_id, kind, memo, entry_date)
     VALUES ($1, 1, 'other', 'empty entry', CURRENT_DATE)`, [uniq('empty')], atok);
  assert(r.status !== 200, 'an entry with no lines was accepted - it is a note pretending to be accounting');
  const check2 = await q('SELECT COUNT(*)::int AS c FROM journal_entries WHERE memo = $1', ['empty entry'], atok);
  assert(check2[0].c === 0, 'the empty entry was committed');
});

await check('the same document cannot be posted twice', async () => {
  // A retried sync or a double-clicked button must not book a sale's revenue
  // entry twice. Enforced by the database, not by remembering to check.
  const cash = await accId('1000');
  const sales = await accId('4000');
  // A fresh source id per run. The journal is append-only, so yesterday's entry
  // for this document is still there and a fixed id would collide on the FIRST
  // insert rather than the second - which is the test measuring the wrong thing.
  const sourceId = 900000 + (Date.now() % 90000);
  const first = await postEntry('sale', sourceId, [
    { account: sales, credit: 250 },
    { account: cash, debit: 250 },
  ]);
  assert(first.status === 200, 'the first post failed: ' + JSON.stringify(first.body));
  const second = await postEntry('sale', sourceId, [
    { account: sales, credit: 250 },
    { account: cash, debit: 250 },
  ]);
  assert(second.status !== 200, 'the same document was posted twice');
  const n = await q(
    "SELECT COUNT(*)::int AS c FROM journal_entries WHERE source_table = 'e2e_journal' AND source_id = $1",
    [sourceId], atok);
  assert(n[0].c === 1, 'there are ' + n[0].c + ' entries for one document');
});

await check('the journal is append-only', async () => {
  // Post a real entry first, so the DELETE has something to refuse. Deleting
  // nothing would return 200 and look like a pass.
  const cash = await accId('1000');
  const e = await postEntry('other', null, [
    { account: cash, debit: 75 },
    { account: cash, credit: 75 },
  ]);
  assert(e.status === 200, 'fixture entry failed: ' + JSON.stringify(e.body));
  const d1 = await exec('DELETE FROM journal_entries WHERE id = $1', [e.id], atok);
  assert(d1.status !== 200, 'a journal ENTRY was deleted - history can be rewritten');
  const d2 = await exec('DELETE FROM journal_lines WHERE entry_id = $1', [e.id], atok);
  assert(d2.status !== 200, 'a journal LINE was deleted - history can be rewritten');
  const still = await q('SELECT COUNT(*)::int AS c FROM journal_entries WHERE id = $1', [e.id], atok);
  assert(still[0].c === 1, 'the entry did not survive the delete attempt');
});

await check('opening balances were posted and the balance sheet balances', async () => {
  const o = await q('SELECT uuid FROM journal_entries WHERE is_opening = TRUE', [], atok);
  assert(o.length === 1, 'expected exactly one opening entry, found ' + o.length);
  const u = await q(
    `SELECT COALESCE(SUM(l.debit),0) AS d, COALESCE(SUM(l.credit),0) AS c
       FROM journal_lines l JOIN journal_entries e ON e.id = l.entry_id
      WHERE e.is_opening = TRUE`, [], atok);
  assert(Number(u[0].d) === Number(u[0].c),
    'the opening entry does not balance: ' + u[0].d + ' vs ' + u[0].c);
  assert(Number(u[0].d) !== 0, 'the opening entry is empty - the shop would look worthless');
});

await check('EVERY entry in the ledger balances', async () => {
  const bad = await q(
    `SELECT entry_id FROM (SELECT entry_id, SUM(debit) d, SUM(credit) c
       FROM journal_lines GROUP BY entry_id) t WHERE d <> c`, [], atok);
  assert(bad.length === 0, 'unbalanced entries: ' + bad.map((b) => b.entry_id).join(', '));
});

console.log('\n' + ok + '/' + total + ' checks passed');
process.exit(ok === total ? 0 : 1);
